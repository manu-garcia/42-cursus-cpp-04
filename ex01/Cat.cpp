#include "Cat.hpp"

#define CAT_TYPE "Cat"

///////////////////////////////////////////////////////////////////////////////
// Constructors / Destructor
///////////////////////////////////////////////////////////////////////////////

Cat::Cat()
{
    type = CAT_TYPE;
    std::cout << "Cat Default constructor." << std::endl;
}

Cat::Cat(const Cat &cat)
{
    *this = cat;
    std::cout << "Cat Copy constructor." << std::endl;
}

Cat::~Cat()
{
    std::cout << "Cat destructor." << std::endl;
}

